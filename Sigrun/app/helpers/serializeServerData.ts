// JSON is parsed as script text before JavaScript sees it. Escape HTML delimiters
// so user-provided strings cannot close the script containing hydration data.
export function serializeServerData(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}
