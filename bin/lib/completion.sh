# Shell completion is handled before runtime discovery: it never needs containers.
completion_applications=(Tyr Forseti Sigrun Bragi Frey Mimir Hugin Gullveig Meili Hermod Skirnir)
completion_words() { printf '%s\n' "$@"; }
completion_candidates() {
  local command=${1:-} service candidate line actions file
  local position=$#
  if (( position == 0 )); then
    completion_words dev local-prod build-images build-base prod source-prod lint test check format autofix deps migrate bootstrap-admin seed i18n proto-gen e2e infra-test db backup maintenance dump-users dump-last-mail restart-watcher task source-task exec shell compose runtime copy stop status logs completion help
    return
  fi
  case "$command" in
    dev) (( position != 1 )) || completion_words --detach ;;
    local-prod) (( position != 1 )) || completion_words registry build local ;;
    prod) (( position != 1 )) || completion_words pull start recreate restart update warmup stop down status logs ;;
    source-prod) (( position != 1 )) || completion_words start compile stop status logs ;;
    completion)
      if (( position == 1 )); then completion_words bash zsh install
      elif (( position == 2 )) && [[ $2 == install ]]; then completion_words bash zsh; fi
      ;;
    seed) (( position != 1 )) || completion_words default big-event tournament ;;
    i18n)
      if (( position == 1 )); then completion_words extract compile
      else completion_words tyr forseti sigrun bragi; fi
      ;;
    e2e) (( position != 1 )) || completion_words dev prepare run ui ;;
    db) (( position != 1 )) || completion_words export import create-frey2 create-mimir2 ensure-mimir-migrations-privileges ;;
    backup) (( position != 1 )) || completion_words pubkey history restore ;;
    maintenance) (( position != 1 )) || completion_words reset migrate-frey1 migrate-mimir1 release-tag ;;
    lint|check|format|autofix|deps)
      completion_words "${completion_applications[@],,}" fenrir
      if [[ $command == deps ]] && (( position == 1 )); then completion_words --update; fi
      ;;
    test)
      completion_words tyr frey mimir gullveig meili hermod hugin forseti sigrun bragi
      if (( position == 1 )); then completion_words --verbose; fi
      ;;
    task|source-task)
      if (( position == 1 )); then
        completion_words "${completion_applications[@],,}"
        [[ $command != task ]] || completion_words common fenrir
      elif (( position == 2 )); then
        service=''
        for candidate in "${completion_applications[@]}" Common Fenrir; do
          [[ ${candidate,,} != "${2,,}" ]] || service=$candidate
        done
        [[ -n $service ]] || return 0
        # Read action labels, never source/execute an application task script.
        for file in "$root/$service/tasks.sh" "$root/Common/ContainerRuntime/service-tasks.sh"; do
          [[ -f $file ]] || continue
          [[ $service != Common || $file != */service-tasks.sh ]] || continue
          while IFS= read -r line; do
            if [[ $line =~ ^[[:space:]]*([a-zA-Z0-9_\|\-]+)\) ]]; then
              IFS='|' read -r -a actions <<< "${BASH_REMATCH[1]}"
              completion_words "${actions[@]}"
            fi
          done < "$file"
        done | sort -u
      fi
      ;;
    shell|exec|copy|restart-watcher|logs)
      if (( position == 1 )) || [[ $command == logs ]]; then
        completion_words "${completion_applications[@],,}" fenrir
        if [[ $command != restart-watcher ]]; then completion_words database redis; fi
      fi
      ;;
  esac
  return 0
}
completion_render() {
  local shell=$1 cli="$root/bin/pantheon" command
  case "$shell" in
    bash)
      cat <<'BASH'
# Pantheon Bash completion. Generated by ./run completion bash.
_pantheon_completion() {
  local current=${COMP_WORDS[COMP_CWORD]} candidate
  COMPREPLY=()
  while IFS= read -r candidate; do
    [[ $candidate != "$current"* ]] || COMPREPLY+=("$candidate")
BASH
      printf '  done < <(%q completion candidates "${COMP_WORDS[@]:1:COMP_CWORD-1}")\n' "$cli"
      cat <<'BASH'
  if (( ${#COMPREPLY[@]} == 0 )); then
    while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -f -- "$current")
  fi
}
BASH
      printf 'complete -o filenames -F _pantheon_completion'
      for command in run ./run pantheon bin/pantheon ./bin/pantheon "$root/run" "$cli"; do printf ' %q' "$command"; done
      printf '\n'
      ;;
    zsh)
      cat <<'ZSH'
# Pantheon Zsh completion. Generated by ./run completion zsh.
if (( ! $+functions[compdef] )); then
  autoload -Uz compinit
  compinit -D
fi
_pantheon_completion() {
  local -a candidates
ZSH
      printf '  candidates=("${(@f)$(%q completion candidates "${words[@]:1:$((CURRENT-2))}")}")\n' "$cli"
      cat <<'ZSH'
  candidates=("${(@)candidates:#}")
  if (( ${#candidates} )); then
    compadd -- "${candidates[@]}"
  else
    _files
  fi
}
ZSH
      printf 'compdef _pantheon_completion'
      for command in run ./run pantheon bin/pantheon ./bin/pantheon "$root/run" "$cli"; do printf ' %q' "$command"; done
      printf '\n'
      ;;
    *) fail 'Supported shells: bash, zsh.' ;;
  esac
}
completion_command() {
  case "${1:-}" in
    candidates) shift; completion_candidates "$@" ;;
    bash|zsh)
      (( $# == 1 )) || fail 'Usage: completion {bash|zsh}'
      completion_render "$1"
      ;;
    install)
      (( $# <= 3 )) || fail 'Usage: completion install [bash|zsh] [RC_FILE]'
      local shell=${2:-${SHELL:-}} rc_file=${3:-} directory target hook
      shell=${shell##*/}
      case "$shell" in
        bash) rc_file=${rc_file:-$HOME/.bashrc} ;;
        zsh) rc_file=${rc_file:-${ZDOTDIR:-$HOME}/.zshrc} ;;
        *) fail 'Usage: completion install {bash|zsh} [RC_FILE]' ;;
      esac
      directory=${PANTHEON_COMPLETION_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/pantheon/completions}
      [[ $directory == /* ]] || directory="$caller_directory/$directory"
      [[ $rc_file == /* ]] || rc_file="$caller_directory/$rc_file"
      target="$directory/pantheon.$shell"
      mkdir -p "$directory" "$(dirname -- "$rc_file")"
      completion_render "$shell" > "$target"
      printf -v hook '[[ ! -r %q ]] || source %q # Pantheon completion' "$target" "$target"
      # An exact managed line makes repeated installation idempotent and leaves
      # user-written shell configuration intact, including a missing final LF.
      if [[ ! -f $rc_file ]] || ! grep -Fqx -- "$hook" "$rc_file"; then
        printf '\n%s\n' "$hook" >> "$rc_file"
      fi
      printf 'Installed %s completion. Restart your shell or run:\n  source %q\n' "$shell" "$target"
      ;;
    *) fail 'Usage: completion {bash|zsh|install [bash|zsh] [RC_FILE]}' ;;
  esac
}
